#!/usr/bin/env python3
"""gen_bridge.py — derive binding tables from src/lt_bridge.h.

Parses every `lt_*` function declaration in lt_bridge.h and emits:

  C++ (for ui/src/Bridge.cpp, via --mode cpp):
    lt_api_members.inc — Api struct members:  decltype(&lt_foo) lt_foo = nullptr;
    lt_api_bind.inc    — BIND(lt_foo) lines for the dlsym loop
    lt_mock_stubs.inc  — static mock_lt_foo() definitions (generic heuristics)
    lt_mock_bind.inc   — api.lt_foo = mock_lt_foo; lines

  Swift (for ui/mockcore, via --mode swift):
    GeneratedStubs.swift — @_cdecl stubs for every non-excluded export

Functions named in --exclude are skipped (hand-written in Bridge.cpp /
MockCore.swift). Run at CMake configure time so the three artifacts can never
drift from the header.

Usage:
  gen_bridge.py --header src/lt_bridge.h --mode cpp --outdir <dir> [--exclude a,b]
  gen_bridge.py --header src/lt_bridge.h --mode swift --out <file> [--exclude a,b]
"""
import argparse
import os
import re
import sys

DECL_RE = re.compile(
    r'^(const char\*|LTResult|int32_t|uint16_t|uint64_t|int64_t|double|void|lt_device_t)'
    r'\s+(lt_\w+)\((.*)\)\s*;\s*$'
)

# C++ type -> Swift type for the mockcore stubs.
SWIFT_TYPES = {
    'LTResult': 'Int32',
    'int32_t': 'Int32',
    'uint16_t': 'UInt16',
    'uint64_t': 'UInt64',
    'int64_t': 'Int64',
    'double': 'Double',
    'void': '()',
    'lt_device_t': 'UInt64',
    'const char*': 'UnsafePointer<CChar>?',
    'const char**': 'UnsafeMutablePointer<UnsafePointer<CChar>?>?',
    'lt_device_t*': 'UnsafeMutablePointer<UInt64>?',
    'int32_t*': 'UnsafeMutablePointer<Int32>?',
    'uint64_t*': 'UnsafeMutablePointer<UInt64>?',
    'const char*ret': 'UnsafePointer<CChar>?',
}


def parse_params(param_str):
    param_str = param_str.strip()
    if param_str in ('void', ''):
        return []
    params = []
    for p in param_str.split(','):
        p = p.strip()
        # split "type name": type may contain spaces ("const char*", "const char**")
        m = re.match(r'^(const char\*\*|const char\*|lt_device_t\*|int32_t\*|uint64_t\*|'
                     r'lt_device_t|int32_t|uint16_t|uint64_t|int64_t|double|void\*|'
                     r'lt_event_fn|const LTEvent\*)\s+(\w+)$', p)
        if not m:
            raise ValueError('cannot parse param %r' % p)
        params.append((m.group(1), m.group(2)))
    return params


def parse_header(path):
    funcs = []
    with open(path) as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            m = DECL_RE.match(line)
            if not m:
                continue
            ret, name, params = m.group(1), m.group(2), m.group(3)
            try:
                parsed = parse_params(params)
            except ValueError as e:
                raise ValueError('%s:%d: %s' % (path, lineno, e))
            funcs.append({'ret': ret, 'name': name, 'params': parsed})
    # lt_last_error returns const char* — normalize its return type key.
    for fn in funcs:
        if fn['name'] == 'lt_last_error':
            fn['ret'] = 'const char*ret'
    return funcs


# Exports whose const char** out-param carries a JSON *array* (everything else
# with a JSON out-param carries an object). Keep in sync with lt_bridge.h §7.
ARRAY_JSON_EXPORTS = frozenset([
    'lt_device_list',
    'lt_jobs_list',
    'lt_catalog_list',
    'lt_log_sources',
    'lt_help_topics',
    'lt_drop_ipsws',
])


def canned_json(name):
    if 'version' in name:
        return '0.0.0-mock'
    if name == 'lt_device_uuid':
        return '00000000-0000-0000-0000-000000000000'
    if name in ARRAY_JSON_EXPORTS:
        return '[]'
    return '{}'


def cpp_param_decl(t, n):
    return '%s %s' % (t, n)


def gen_cpp(funcs, mock_funcs, outdir):
    with open(os.path.join(outdir, 'lt_api_members.inc'), 'w') as f:
        f.write('// GENERATED by cmake/gen_bridge.py — do not edit.\n')
        for fn in funcs:
            # &:: — the member name shadows the global; qualify explicitly.
            f.write('decltype(&::%s) %s = nullptr;\n' % (fn['name'], fn['name']))
    with open(os.path.join(outdir, 'lt_api_bind.inc'), 'w') as f:
        f.write('// GENERATED by cmake/gen_bridge.py — do not edit.\n')
        for fn in funcs:
            f.write('BIND(%s);\n' % fn['name'])
    with open(os.path.join(outdir, 'lt_mock_stubs.inc'), 'w') as f:
        f.write('// GENERATED by cmake/gen_bridge.py — do not edit.\n')
        f.write('// Generic mock implementations. Heuristics: queries fill out-params\n')
        f.write('// with canned JSON and return kLTOk; bare commands return kLTAccepted.\n')
        f.write('#include <cstring>\n#include <cstdlib>\n')
        for fn in mock_funcs:
            name, ret, params = fn['name'], fn['ret'], fn['params']
            f.write('\nstatic %s mock_%s(%s) {\n'
                    % (ret, name, ', '.join(cpp_param_decl(t, n) for t, n in params)
                       if params else 'void'))
            out_strings = [(t, n) for t, n in params if t == 'const char**']
            out_scalars = [(t, n) for t, n in params
                           if t in ('lt_device_t*', 'int32_t*', 'uint64_t*')]
            used = set()
            for t, n in out_strings:
                f.write('    if (%s) *%s = strdup("%s");\n'
                        % (n, n, canned_json(name).replace('"', '\\"')))
                used.add(n)
            for t, n in out_scalars:
                if name == 'lt_drop_classify':
                    f.write('    if (%s) *%s = kLTDropUnsupported;\n' % (n, n))
                else:
                    f.write('    if (%s) *%s = 0;\n' % (n, n))
                used.add(n)
            for t, n in params:
                if n not in used:
                    f.write('    (void)%s;\n' % n)
            if ret == 'LTResult':
                f.write('    return %s;\n'
                        % ('kLTOk' if (out_strings or out_scalars) else 'kLTAccepted'))
            elif ret == 'int32_t':
                f.write('    return %s;\n' % ('1' if name == 'lt_abi_version' else '0'))
            elif ret == 'double':
                f.write('    return %s;\n' % ('-1.0' if name == 'lt_zoom_step' else '0.0'))
            elif ret == 'uint64_t':
                f.write('    return 0;\n')
            elif ret == 'const char*ret':
                f.write('    return strdup("mock");\n')
            f.write('}\n')
    with open(os.path.join(outdir, 'lt_mock_bind.inc'), 'w') as f:
        f.write('// GENERATED by cmake/gen_bridge.py — do not edit.\n')
        for fn in mock_funcs:
            f.write('api.%s = mock_%s;\n' % (fn['name'], fn['name']))


def swift_stub(fn):
    name, ret, params = fn['name'], fn['ret'], fn['params']
    stype = SWIFT_TYPES[ret]
    sparams = ', '.join('_ %s: %s' % (n, SWIFT_TYPES[t]) for t, n in params)
    lines = ['@_cdecl("%s")' % name,
             'public func %s(%s)%s {' % (name, sparams,
                                         '' if stype == '()' else ' -> ' + stype)]
    for t, n in params:
        if t == 'const char**':
            lines.append('    %s?.pointee = UnsafePointer<CChar>(strdup("%s"))'
                         % (n, canned_json(name).replace('"', '\\"')))
        elif t in ('lt_device_t*', 'int32_t*', 'uint64_t*'):
            lines.append('    %s?.pointee = %s' % (n, '3' if name == 'lt_drop_classify' else '0'))
    if ret == 'LTResult':
        lines.append('    return %s  /* %s */'
                     % (0, 'kLTOk' if any(t.endswith('*') for t, _ in params) else 'kLTAccepted'))
    elif ret == 'int32_t':
        lines.append('    return %d' % (1 if name == 'lt_abi_version' else 0))
    elif ret == 'double':
        lines.append('    return %s' % ('-1.0' if name == 'lt_zoom_step' else '0.0'))
    elif ret == 'uint64_t':
        lines.append('    return 0')
    elif ret == 'const char*ret':
        lines.append('    return UnsafePointer<CChar>(strdup("mock"))')
    lines.append('}')
    return '\n'.join(lines)


def gen_swift(mock_funcs, out):
    with open(out, 'w') as f:
        f.write('// GENERATED by cmake/gen_bridge.py — do not edit.\n')
        f.write('// Generic mock implementations for the Swift stand-in library.\n')
        f.write('// See MockCore.swift for the hand-written interesting ones.\n')
        f.write('import Foundation\n')
        f.write('#if canImport(Darwin)\nimport Darwin\n')
        f.write('#elseif canImport(Glibc)\nimport Glibc\n#endif\n\n')
        for fn in mock_funcs:
            f.write(swift_stub(fn) + '\n\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--header', required=True)
    ap.add_argument('--mode', required=True, choices=('cpp', 'swift'))
    ap.add_argument('--outdir', default=None)
    ap.add_argument('--out', default=None)
    # Functions skipped by the MOCK emitters only (hand-written mocks).
    # The Api struct and dlsym bind list always cover every export.
    ap.add_argument('--mock-exclude', default='')
    args = ap.parse_args()

    mock_excluded = set(e for e in args.mock_exclude.split(',') if e)
    funcs = parse_header(args.header)
    mock_funcs = [fn for fn in funcs if fn['name'] not in mock_excluded]
    names = [fn['name'] for fn in funcs]
    if len(names) != len(set(names)):
        sys.exit('duplicate lt_ declarations in header')

    if args.mode == 'cpp':
        if not args.outdir:
            sys.exit('--outdir required for cpp mode')
        os.makedirs(args.outdir, exist_ok=True)
        gen_cpp(funcs, mock_funcs, args.outdir)
    else:
        if not args.out:
            sys.exit('--out required for swift mode')
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        gen_swift(mock_funcs, args.out)
    print('gen_bridge.py: %d functions (%d mock) -> %s'
          % (len(funcs), len(mock_funcs), args.mode))


if __name__ == '__main__':
    main()
